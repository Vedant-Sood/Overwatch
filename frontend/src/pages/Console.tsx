import { useEffect, useState } from "react";
import { api } from "../api";
import type { Ctx } from "../App";
import { Action, ErrorBox, ModeBadge, SimBanner } from "../components/ui";
import { Thesis } from "./Scanner";

export default function ConsolePage({ ctx }: { ctx: Ctx }) {
  const [q, setQ] = useState("");
  const [r, setR] = useState<any>(null);
  const [busy, setBusy] = useState(false);
  const [err, setErr] = useState<unknown>(null);
  const [reports, setReports] = useState<any[]>([]);
  const loadReports = () => api.get(`/api/agents/reports?mode=${ctx.mode}`).then(setReports).catch(() => setReports([]));
  useEffect(() => { setR(null); loadReports(); }, [ctx.mode]);

  const ask = async () => {
    setBusy(true); setErr(null);
    try { setR(await api.post("/api/agents/research", { mode: ctx.mode, question: q })); loadReports(); } catch (e) { setErr(e); } finally { setBusy(false); }
  };
  const open = async (id: string) => { try { setR(await api.get(`/api/agents/reports/${id}?mode=${ctx.mode}`)); } catch (e) { setErr(e); } };

  return (
    <div>
      <div className="page-head"><h1>BigBoss AI Research Console</h1><ModeBadge mode={ctx.mode} /></div>
      <SimBanner mode={ctx.mode} />
      <div className="card">
        <textarea value={q} onChange={(e) => setQ(e.target.value)} placeholder={ctx.mode === "synthetic" ? "e.g. Should I buy SYN003? What are the risks? Build me a balanced portfolio." : "e.g. Is MSFT attractive over the next month? What does the latest filing say? What are the risks?"} />
        <div className="row" style={{ marginTop: 8 }}>
          <button className="btn primary" disabled={busy || q.trim().length < 3} onClick={ask}>{busy ? "Agents working…" : "Run research workflow"}</button>
          <span className="muted" style={{ fontSize: 12 }}>Agents call deterministic tools; {ctx.health?.llm?.available ? `the local LLM (${ctx.health.llm.provider}) only writes the summary and is rejected if it invents numbers` : "no LLM is configured, so summaries are deterministic templates"}.</span>
        </div>
      </div>
      <ErrorBox error={err} />
      <div className="grid" style={{ gridTemplateColumns: "1fr 260px", marginTop: 14, alignItems: "start" }}>
        <div>
          {r && <>
            <div className="card">
              <h3>Answer <span className="muted" style={{ fontWeight: 400 }}>· {r.report_id} · {r.created_at} · generated by {r.narrative.generator}</span></h3>
              {r.narrative.rejected_numbers?.length > 0 && <div className="banner warn">LLM draft discarded: it contained numbers not in the evidence ({r.narrative.rejected_numbers.join(", ")}).</div>}
              <pre className="mono">{r.narrative.text}</pre>
            </div>
            {r.decisions.map((d: any) => (
              <div className="card" key={d.symbol} style={{ marginTop: 14 }}>
                <h3>Investment committee · {d.symbol} · quant <Action a={d.quant_action || "INSUFFICIENT_EVIDENCE"} /> → final <Action a={d.final_action} /> · size {(d.suggested_weight * 100).toFixed(1)}%</h3>
                {d.disagreements.length > 0 && <div className="banner warn"><strong>Documented disagreements:</strong><ul className="tight">{d.disagreements.map((x: string) => <li key={x}>{x}</li>)}</ul></div>}
                {d.vetoes.length > 0 && <div className="banner err"><strong>Risk vetoes:</strong> {d.vetoes.join("; ")}</div>}
                <Thesis t={d.thesis} />
              </div>
            ))}
            <div className="card" style={{ marginTop: 14 }}>
              <h3>Agent audit trail</h3>
              {r.agents.map((a: any, i: number) => (
                <details key={i} style={{ marginBottom: 6 }}>
                  <summary><strong>{a.agent}</strong> <span className={a.status === "ok" ? "pos" : "neg"}>{a.status}</span> · {a.findings.length} findings · {a.tool_calls.length} tool calls</summary>
                  <ul className="tight">{a.findings.map((f: any, j: number) => <li key={j}>{f.statement} <span className="muted">[{f.source}{f.as_of ? ` @ ${f.as_of}` : ""}]</span></li>)}</ul>
                  {a.warnings.length > 0 && <ul className="tight">{a.warnings.map((w: string) => <li key={w} className="neg">⚠ {w}</li>)}</ul>}
                  {a.tool_calls.length > 0 && <pre className="mono">{a.tool_calls.map((t: any) => `${t.started_at} ${t.tool}(${JSON.stringify(t.args)}) ${t.ok ? "ok" : "FAILED " + t.error} ${t.duration_ms.toFixed(0)}ms sha256=${(t.output_sha256 || "").slice(0, 12)}`).join("\n")}</pre>}
                </details>
              ))}
              <div className="muted" style={{ fontSize: 12 }}>Reproducibility: {JSON.stringify(r.reproducibility)}</div>
            </div>
          </>}
        </div>
        <div className="card"><h3>Saved reports</h3>
          {reports.map((x) => <div key={x.report_id} style={{ marginBottom: 6 }}><a href="#/console" onClick={(e) => { e.preventDefault(); open(x.report_id); }}>{x.question.slice(0, 60)}</a><div className="muted" style={{ fontSize: 11 }}>{x.created_at.slice(0, 19)}</div></div>)}
          {!reports.length && <div className="muted">None yet.</div>}
        </div>
      </div>
    </div>
  );
}
